"""Writes reports/MODEL_CARD.md and the evaluation figures from the generated result files.

Nothing here is typed by hand: every number, and every comparative word such as
"significant", is read or derived from the JSON files written by
ml.train_classifier, ml.temporal_eval and ml.trends. Re-run this after any of them.

Usage:
  python -m ml.model_card
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np

from ml import plot_style as style

plt = style.plt
MODEL_NAMES = {"linear_svm": "TF-IDF + Linear SVM", "multinomial_nb": "TF-IDF + Naive Bayes",
               "majority_class": "Majority class"}


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--reports-dir", default=Path("reports"), type=Path)
    parser.add_argument("--random-run", default="svm_tfidf_v1")
    parser.add_argument("--temporal-run", default="svm_tfidf_v1_temporal")
    return parser.parse_args(argv)


def load(path):
    if not path.is_file():
        sys.exit(f"Missing {path}. Run the step that produces it first (see docs/dataset.md).")
    return json.loads(path.read_text(encoding="utf-8"))


def f(value, digits=4):
    return "n/a" if value is None else f"{value:.{digits}f}"


def pct(value, digits=1):
    return f"{value * 100:.{digits}f}%"


def change(drop):
    """drop = random-split score minus temporal-split score."""
    if abs(drop) < 0.0005:
        return "essentially unchanged"
    return f"{'falls' if drop > 0 else 'rises'} by {abs(drop) * 100:.1f} points"


def p_text(p):
    return "p < 0.001" if p < 0.001 else f"p = {p:.3f}"


# ---------------------------------------------------------------- figures

def bar_value_labels(ax, bars, values):
    for bar, value in zip(bars, values):
        ax.annotate(f"{value:.3f}", (bar.get_width(), bar.get_y() + bar.get_height() / 2), xytext=(6, 0),
                    textcoords="offset points", va="center", color=style.INK_SECONDARY, fontsize=10)


def figure_models(path, random_m, temporal_m):
    models = ["linear_svm", "multinomial_nb", "majority_class"]
    fig, ax = plt.subplots(figsize=(11, 4.8))
    y = np.arange(len(models))[::-1]
    height = 0.32
    splits = [("Random 80/20 split", random_m, style.SERIES[0]),
              (f"Temporal split (train {temporal_m['split']['train_years'][0]}–{temporal_m['split']['train_years'][1]},"
               f" test {temporal_m['split']['test_years'][0]}–{temporal_m['split']['test_years'][1]})",
               temporal_m, style.SERIES[1])]
    for offset, (label, metrics, color) in zip((height / 2 + 0.02, -height / 2 - 0.02), splits):
        values = [metrics["models"][m]["test"]["macro_f1"] for m in models]
        bars = ax.barh(y + offset, values, height=height, color=color, label=label)
        bar_value_labels(ax, bars, values)
    ax.set_yticks(y, [MODEL_NAMES[m] for m in models])
    ax.set_xlim(0, 1.08)
    ax.xaxis.set_major_formatter(style.FuncFormatter(lambda v, _p: f"{v:.1f}"))
    ax.grid(axis="y", visible=False)
    ax.grid(axis="x", visible=True)
    ax.set_xlabel("Macro-F1 on the held-out test set (higher is better)")
    ax.set_title("Topic classifier: test macro-F1 by model and evaluation split", pad=26)
    style.subtitle(ax, f"5 arXiv categories; {random_m['split']['test_total']:,} unseen test papers per split. "
                       "Same models, parameters chosen by 5-fold CV on training data only.")
    ax.legend(loc="lower right")  # the majority-class bars leave this corner empty
    style.source_note(fig, "Source: reports/svm_tfidf_v1*/metrics.json (generated by ml.train_classifier "
                           "and ml.temporal_eval).")
    style.save(fig, path)


def figure_per_category(path, random_m, temporal_m):
    labels = random_m["labels"]
    order = sorted(labels, key=lambda c: random_m["models"]["linear_svm"]["test"]["per_class"][c]["f1"])
    fig, ax = plt.subplots(figsize=(11, 5.2))
    y = np.arange(len(order))
    height = 0.34
    for offset, (label, metrics, color) in zip(
            (height / 2 + 0.02, -height / 2 - 0.02),
            [("Random split", random_m, style.SERIES[0]), ("Temporal split", temporal_m, style.SERIES[1])]):
        values = [metrics["models"]["linear_svm"]["test"]["per_class"][c]["f1"] for c in order]
        bars = ax.barh(y + offset, values, height=height, color=color, label=label)
        bar_value_labels(ax, bars, values)
    ax.set_yticks(y, [f"{c}  {style.CATEGORY_NAMES[c]}" for c in order])
    ax.set_xlim(0, 1.08)
    ax.grid(axis="y", visible=False)
    ax.grid(axis="x", visible=True)
    ax.set_xlabel("F1 score per category, Linear SVM (higher is better)")
    ax.set_title("Linear SVM: F1 per category on unseen test papers", pad=26)
    style.subtitle(ax, "400 test papers per category in each split. Categories ordered by random-split F1.")
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.14), ncol=2)
    style.source_note(fig, "Source: reports/svm_tfidf_v1*/metrics.json.")
    style.save(fig, path)


# ---------------------------------------------------------------- card

def results_table(random_m, temporal_m):
    rows = ["| Model | Split | Accuracy | Macro precision | Macro recall | Macro-F1 | CV macro-F1 (train) |",
            "|---|---|---|---|---|---|---|"]
    for name in ("linear_svm", "multinomial_nb", "majority_class"):
        for split_name, m in (("random", random_m), ("temporal", temporal_m)):
            r = m["models"][name]
            t = r["test"]
            cv = f"{f(r['cv_macro_f1_mean'])} ± {f(r['cv_macro_f1_std'])}" if r["cv_macro_f1_mean"] is not None else "n/a"
            rows.append(f"| {MODEL_NAMES[name]} | {split_name} | {f(t['accuracy'])} | {f(t['macro_precision'])} | "
                        f"{f(t['macro_recall'])} | {f(t['macro_f1'])} | {cv} |")
    return "\n".join(rows)


def per_class_table(random_m, temporal_m):
    rows = ["| Category | Precision (random) | Recall (random) | F1 (random) | F1 (temporal) |",
            "|---|---|---|---|---|"]
    for c in random_m["labels"]:
        r = random_m["models"]["linear_svm"]["test"]["per_class"][c]
        t = temporal_m["models"]["linear_svm"]["test"]["per_class"][c]
        rows.append(f"| {c} {style.CATEGORY_NAMES[c]} | {f(r['precision'], 3)} | {f(r['recall'], 3)} | "
                    f"{f(r['f1'], 3)} | {f(t['f1'], 3)} |")
    return "\n".join(rows)


def comparison_sentence(m, split_name):
    s = m["svm_vs_nb"]
    svm, nb = m["models"]["linear_svm"]["test"]["macro_f1"], m["models"]["multinomial_nb"]["test"]["macro_f1"]
    better = "higher" if svm > nb else "lower" if svm < nb else "equal"
    verdict = ("This difference is statistically significant" if s["significant_at_0.05"]
               else "This difference is **not** statistically significant")
    return (f"- **{split_name} split:** the SVM's macro-F1 ({f(svm)}) is {better} than Naive Bayes ({f(nb)}). "
            f"On the same test papers, {s['only_svm_correct']} were classified correctly only by the SVM and "
            f"{s['only_nb_correct']} only by Naive Bayes. {verdict} (exact McNemar test, {p_text(s['p_value'])}).")


def build_card(random_m, temporal_m, manifest, info, trends):
    svm_r = random_m["models"]["linear_svm"]["test"]
    svm_t = temporal_m["models"]["linear_svm"]["test"]
    per_class = svm_r["per_class"]
    weakest = min(per_class, key=lambda c: per_class[c]["f1"])
    strongest = max(per_class, key=lambda c: per_class[c]["f1"])
    drop = svm_r["macro_f1"] - svm_t["macro_f1"]
    nb_drop = (random_m["models"]["multinomial_nb"]["test"]["macro_f1"]
               - temporal_m["models"]["multinomial_nb"]["test"]["macro_f1"])
    split_t = temporal_m["split"]
    years = temporal_m["by_test_year"]
    year_lines = "\n".join(
        f"| {y} | {v['n']} | {f(v['linear_svm']['accuracy'])} | {f(v['linear_svm']['macro_f1'])} | "
        f"{f(v['multinomial_nb']['macro_f1'])} |" for y, v in years.items())
    ds = manifest["dataset"]
    sample = manifest["sample"]
    filt = manifest["filtering"]
    cats = ", ".join(f"`{c}`" for c in manifest["parameters"]["categories"])

    trend_section = ""
    if trends:
        last = trends["dataset"]["last_full_year"]
        base = trends["parameters"]["index_base_year"]
        lines = "\n".join(
            f"| {c} | {v[f'papers_{base}']:,} | {v[f'papers_{last}']:,} | ×{v['growth_multiple']:.2f} | "
            f"{pct(v['cagr'])} | {pct(v[f'share_of_cs_{last}'])} | {', '.join(v['top_rising_keywords'][:3])} |"
            for c, v in trends["categories"].items())
        trend_section = f"""
## 7. Related output: historical trend analysis (descriptive, not a model)

`ml/trends.py` counts **all** papers in the snapshot (not the training sample). The snapshot ends on
{trends['dataset']['latest_submission']}, so {last} is the last full year. Results are in `reports/trends/`
and figures 01–04 in `reports/figures/`.

| Category | Papers {base} | Papers {last} | Growth | Annual growth (CAGR) | Share of CS papers {last} | Fastest-rising keywords |
|---|---|---|---|---|---|---|
{lines}

These are publication statistics. They show what is being published on arXiv. They do **not** forecast the
future, measure research quality, or identify research gaps.
"""

    return f"""# Model card: research topic classifier (TF-IDF + Linear SVM)

*Generated by `python -m ml.model_card` from the result files. Do not edit by hand; re-run it instead.*

Component 3 (Research Intelligence & Collaboration Ecosystem), module 5: research trend analysis.

## 1. Model details

| | |
|---|---|
| Model | `{info['model']}` |
| Run | `{info['run_name']}`, trained {info['created_at']} |
| Selected hyperparameter | {', '.join(f'{k} = {v}' for k, v in info['best_params'].items())} (5-fold CV, macro-F1) |
| Input | Paper title + abstract, cleaned by `ml.text_utils.build_text` |
| Output | One of {len(info['labels'])} arXiv categories: {', '.join(info['labels'])} |
| Training data | {info['train_size']:,} papers (training split only) |
| Libraries | Python {info['versions']['python']}, scikit-learn {info['versions']['scikit-learn']}, numpy {info['versions']['numpy']} |

## 2. Intended use

- **Intended use:** suggest which of the five research areas a project title and abstract is closest to.
  The result gives context for the trend analysis (for example, "your proposal is closest to cs.RO;
  here is how cs.RO publishing has developed").
- **Not intended for:**
  - detecting research gaps or judging novelty;
  - assessing the quality of a proposal or a student;
  - any grading decision;
  - texts outside these five areas.
- **No "other" class.** The model always answers with one of the five categories, even for an unrelated
  text, so its output must be shown as "closest of five areas", never as a verified classification.

## 3. Training data

- **Source:** Cornell arXiv metadata snapshot (Kaggle), `{ds['file']}`:
  - {ds['records_read']:,} records, {ds['malformed_lines']} malformed;
  - SHA-256 `{ds['sha256']}`.
- **Categories:** {cats}. `cs.LG` and `cs.AI` are deliberately left out of this first version, because
  they are broad and heavily cross-listed.
- **Label:** {manifest['label_policy']}
- **Filters:** first submitted {manifest['parameters']['years'][0]}–{manifest['parameters']['years'][1]};
  abstracts of at least {manifest['parameters']['min_abstract_words']} words.
  - {filt['dropped_short_or_empty']} papers were removed as too short.
  - {filt['dropped_duplicate_title']} were removed as duplicate titles; every copy was dropped.
- **Sample:**
  - {sample['total']:,} papers, {', '.join(f'{c}: {n:,}' for c, n in sample['by_category'].items())};
  - drawn by a seeded hash ranking, so it is reproducible (sample SHA-256 `{sample['content_sha256'][:16]}…`).
- **Cross-listing:**
  - {pct(sample['cross_listed_share'])} of the sampled papers are cross-listed to some other category;
  - {pct(sample['cross_listed_within_selected_share'])} are cross-listed to another of the five. These are
    the inherently ambiguous cases.

## 4. Evaluation protocol

Two evaluations use the same models, the same hyperparameter grids and the same test size.

1. **Random split.**
   - Stratified 80/20 split with seed {random_m['split']['seed']}:
     {random_m['split']['train_total']:,} training papers and {random_m['split']['test_total']:,} test papers.
   - It measures performance on papers from the same period as the training data.
2. **Temporal split.**
   - Train on papers first submitted {split_t['train_years'][0]}–{split_t['train_years'][1]}.
   - Test on papers from {split_t['test_years'][0]}–{split_t['test_years'][1]}.
   - Sizes: {split_t['train_total']:,} training papers and {split_t['test_total']:,} test papers.
   - It measures how well the model carries over to newer research.

Leakage controls, applied to both:
- the split happens before any fitting;
- no paper id or normalised title appears in both train and test (checked, and the run stops if one does);
- TF-IDF is fitted inside the pipeline on training data only;
- hyperparameters are chosen by 5-fold CV on the training data only;
- each model scores the test set once.

Baselines go through the identical protocol: majority class, and TF-IDF + Multinomial Naive Bayes.

## 5. Results (held-out test sets)

{results_table(random_m, temporal_m)}

### SVM compared with Naive Bayes

{comparison_sentence(random_m, 'Random')}
{comparison_sentence(temporal_m, 'Temporal')}

### Effect of time

Moving from the random split to the temporal split changes macro-F1 as follows:
- SVM: {f(svm_r['macro_f1'])} → {f(svm_t['macro_f1'])}, {change(drop)}.
- Naive Bayes: {change(nb_drop)}.

Breakdown of the temporal test set by year:

| Test year | Papers | SVM accuracy | SVM macro-F1 | Naive Bayes macro-F1 |
|---|---|---|---|---|
{year_lines}

The test papers within each year are not exactly balanced across categories, so the yearly figures are
indicative only.

### Per category (Linear SVM)

{per_class_table(random_m, temporal_m)}

- **Weakest category in the random split:** {weakest} ({style.CATEGORY_NAMES[weakest]}), F1 {f(per_class[weakest]['f1'], 3)}.
- **Strongest:** {strongest} ({style.CATEGORY_NAMES[strongest]}), F1 {f(per_class[strongest]['f1'], 3)}.
- The confusion matrices are in `reports/<run>/confusion_matrix.png`.
- The papers each model got wrong are in `reports/<run>/misclassified_test.csv`.

Figures: `reports/figures/05_model_comparison.png` and `reports/figures/06_per_category_f1.png`.

## 6. Limitations

- **What the score measures.** It measures how well the model reproduces the authors' own choice of
  primary arXiv category among five fairly distinct areas. It is **not** a measure of research-gap
  detection, novelty or quality.
- **More categories will be harder.** Adding more, or closer, categories (for example `cs.LG` and `cs.AI`)
  is expected to lower the scores.
- **Labels are self-assigned.** Primary categories are chosen by the authors. Cross-listed and
  interdisciplinary papers have no single correct answer.
- **Language and source.** The model reads only English titles and abstracts from arXiv. Project proposals
  written in a different style may score differently, and this has not been measured.
- **Vocabulary drift.** Performance falls on later years (section 5). The model should be retrained
  periodically on newer papers.
{trend_section}
## 8. Reproduce

```powershell
cd ml-service
.\\.venv\\Scripts\\Activate.ps1
python -m ml.prepare_data --input data/raw/arxiv-metadata-oai-snapshot.json --seed 42
python -m ml.train_classifier --data data/processed/sample.jsonl.gz --seed 42
python -m ml.temporal_eval --input data/raw/arxiv-metadata-oai-snapshot.json --seed 42
python -m ml.trends --input data/raw/arxiv-metadata-oai-snapshot.json
python -m ml.model_card
```
"""


def main(argv=None):
    args = parse_args(argv)
    style.apply()
    random_dir = args.reports_dir / args.random_run
    random_m = load(random_dir / "metrics.json")
    temporal_m = load(args.reports_dir / args.temporal_run / "metrics.json")
    manifest = load(random_dir / "data_manifest.json")
    info = load(random_dir / "model_info.json")
    trends_path = args.reports_dir / "trends" / "trends_summary.json"
    trends = load(trends_path) if trends_path.is_file() else None

    figures = args.reports_dir / "figures"
    figure_models(figures / "05_model_comparison.png", random_m, temporal_m)
    figure_per_category(figures / "06_per_category_f1.png", random_m, temporal_m)
    card = build_card(random_m, temporal_m, manifest, info, trends)
    (args.reports_dir / "MODEL_CARD.md").write_text(card, encoding="utf-8")
    print(f"Wrote {args.reports_dir / 'MODEL_CARD.md'} and figures 05-06 in {figures}", file=sys.stderr)


if __name__ == "__main__":
    main()
